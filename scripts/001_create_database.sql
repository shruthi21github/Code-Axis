-- ============================================================================
-- Create Database
-- ============================================================================

CREATE DATABASE IF NOT EXISTS code_axis_db
CHARACTER SET utf8mb4
COLLATE utf8mb4_unicode_ci;

-- ============================================================================
-- Select Database
-- ============================================================================

USE code_axis_db;

-- ============================================================================
-- Session Configuration
-- ============================================================================

SET NAMES utf8mb4;
SET time_zone = '+00:00';

-- ============================================================================
-- Database Architecture Standards
-- ============================================================================

/*
------------------------------------------------------------------------------
GENERAL RULES
------------------------------------------------------------------------------
1. snake_case naming convention
2. UUIDv7 generated in backend
3. UUID stored as BINARY(16)
4. UTC timestamps only
5. Soft delete enabled
6. Audit columns enabled
7. Lookup tables instead of ENUM
8. SQL-first architecture
9. Strict foreign key constraints
10. Manual schema management
------------------------------------------------------------------------------

------------------------------------------------------------------------------
PRIMARY KEY STANDARD
------------------------------------------------------------------------------
Column Format:
    pk_table_name_id

Examples:
    pk_user_id
    pk_project_id
------------------------------------------------------------------------------

------------------------------------------------------------------------------
FOREIGN KEY STANDARD
------------------------------------------------------------------------------
Column Format:
    fk_referenced_table_id

Constraint Format:
    fk_table_name_column_name

Examples:
    fk_role_id
    fk_users_role_id
------------------------------------------------------------------------------

------------------------------------------------------------------------------
INDEX STANDARD
------------------------------------------------------------------------------
Index Format:
    idx_table_name_column_name
------------------------------------------------------------------------------

------------------------------------------------------------------------------
COMMON AUDIT COLUMNS
------------------------------------------------------------------------------
created_at
created_by
updated_at
updated_by
------------------------------------------------------------------------------

------------------------------------------------------------------------------
COMMON SOFT DELETE COLUMNS
------------------------------------------------------------------------------
is_deleted
deleted_at
------------------------------------------------------------------------------

------------------------------------------------------------------------------
COMMON ACTIVE STATUS COLUMN
------------------------------------------------------------------------------
is_active
------------------------------------------------------------------------------
*/

-- ============================================================================
-- Schema Validation Queries
-- ============================================================================

SELECT
    SCHEMA_NAME AS database_name,
    DEFAULT_CHARACTER_SET_NAME AS character_set,
    DEFAULT_COLLATION_NAME AS collation_name
FROM information_schema.SCHEMATA
WHERE SCHEMA_NAME = 'code_axis_db';

